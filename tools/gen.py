import zdis, capstone, numpy as np, re, hashlib
from capstone import x86
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64); md.detail = True
p = zdis.pe()
text = [s for s in p.sections if s.Name.startswith(b'.text')][0]
traw = zdis._data[text.PointerToRawData:text.PointerToRawData+text.SizeOfRawData]

def sig(rva, n=40):
    code = zdis.read(rva, n + 16)
    b = bytearray(); m = bytearray()
    for ins in md.disasm(code, rva):
        if ins.address - rva >= n: break
        ib = bytearray(ins.bytes); im = bytearray(b'\xff' * len(ib))
        rip = any(op.type == x86.X86_OP_MEM and op.mem.base == x86.X86_REG_RIP for op in ins.operands)
        if rip and ins.disp_size:
            for k in range(ins.disp_offset, ins.disp_offset + ins.disp_size): im[k] = 0
        if ins.group(capstone.CS_GRP_JUMP) or ins.group(capstone.CS_GRP_CALL):
            if ins.operands and ins.operands[0].type == x86.X86_OP_IMM and ins.imm_size:
                for k in range(ins.imm_offset, ins.imm_offset + ins.imm_size): im[k] = 0
        b += ib; m += im
    return bytes(b), bytes(m)

def count(b, m):
    # count matches in .text (numpy filter by first unmasked 4 bytes)
    fixed = [i for i in range(len(b)) if m[i]]
    i0 = fixed[0]
    cands = [mm.start() - i0 for mm in re.finditer(re.escape(b[i0:i0+4]), traw)]
    n = 0
    for c in cands:
        if c < 0: continue
        if all(traw[c+i] == b[i] for i in fixed): n += 1
    return n

